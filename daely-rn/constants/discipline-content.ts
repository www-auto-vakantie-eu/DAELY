// Central discipline content structure
// Each discipline has: workouts, exercises, programs

export interface Workout {
  id: string;
  name: string;
  muscle: string;
  duration: string;
  level: string;
  icon: string;
  color: string;
  exercises: number;
}

export interface Exercise {
  id: string;
  name: string;
  spiergroep: string;
  categorie: string;
  moeilijkheid: 'Beginner' | 'Gemiddeld' | 'Gevorderd';
  instructions?: string[];
  techniqueTips?: string[];
  commonMistakes?: string[];
  alternatives?: string[];
  safetyNotes?: string[];
  equipment?: string[];
  mediaItems?: Array<{
    id: string;
    type: 'demo_video' | 'muscle_highlight' | 'illustration';
    title: string;
    description?: string;
    asset?: string;
    thumbnail?: string;
  }>;
}

export interface Program {
  id: string;
  name: string;
  duration: string;
  level: string;
  weeks: number;
  description?: string;
  goal?: string;
  daysPerWeek?: number;
  workoutIds?: string[];
  sourceType?: 'daely' | 'coach' | 'influencer';
  creatorId?: string;
  creatorName?: string;
  creatorRole?: string;
  accessType?: 'included' | 'paid';
  priceLabel?: string;
  isOwned?: boolean;
}

export interface DisciplineContent {
  workouts: Workout[];
  exercises: Exercise[];
  programs: Program[];
}

